"""Baseplate geometry: which local cells each `LayerKind` is measured to occupy.

Open unknown #3, answered from the corpus on 2026-08-21 and confirmed on the
render channel the same day. A layer does not carry its own extent on the wire
-- it carries a `world_hex_position` and a list of occupied cells -- so "is this
cell on a plate" is not a field to read but a fact to measure. These footprints
are that measurement.

Provenance, regenerated by `scripts/probe_plate_footprint.py` against the
course corpus (`decisions.md` 2026-08-18: binaries stay out of the repo,
reproducibility comes from the committed script): 808 files, 640 parsed, 77
skipped as v2 and 31 as v7 by declared version, 60 further parse failures
recorded rather than swallowed.

**Positive evidence only, in the same sense as the port records.** A position
absent from a footprint has never been observed; across 28,494 BASE_LAYER_PIECE
placements that is strong, and it is still not proof the app forbids it.

The render channel tested the operative half on 2026-08-21 and it held, on
**two cells**: E and SW from BASE_LAYER_PIECE local (0, 1), both port-allowed
and both off the footprint, both rendered inactive. That is what refuted the
port-only model. It is not a rendered survey of the footprint's boundary, and
this module should not be read as one -- "off-plate kills everywhere" is the
model's extrapolation, held at UNMEASURED by `graph.py` exactly like any other.

*Why* it kills stays open unknown #17: the cell may have no plate under it, or
the format may store coordinates inside a canonical window with
`world_hex_position` absorbing the offset. Both readings predict the same thing
here, which is why this module states the footprint and not the reason.

Two structural facts worth having in view, because they are why the corner
matters. `LARGE_LAYER` (19 cells) and `SMALL_LAYER` (7 cells) are hexagons
*centred* on their local origin, so all six neighbours of (0,0) are occupied in
the corpus. `BASE_LAYER_PIECE` (30 cells) is not: its local origin sits on a
boundary with W, SW and SE unobserved in every one of those 28,494 placements.
Every sweep through 2026-08-10 pinned the STARTER at that origin, which is
where the live-direction table's 2-vs-1 asymmetry came from -- see
`graph.py` and `decisions.md` 2026-08-21.

`BASE_LAYER` and `LARGE_GHOST_LAYER` are **unmeasured**, not empty: the corpus
shows zero cells on either, and zero observations of something the corpus may
simply not record means invisible, not absent (`decisions.md` 2026-08-21, "Ask
what the corpus can see"). Asking about them raises rather than answering
`False`.
"""

