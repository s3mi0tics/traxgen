# Generated by scripts/probe_plate_arrangement.py against the same corpus, never
# hand-typed, for the same reason as the footprints above. The modal four-plate
# arrangement: 228 of the 241 four-plate courses use exactly this set of world
# positions. Measured as a *set* rather than inferred from four marginal
# frequencies. Of the 11 distinct four-plate sets, **8 are this shape
# translated and 3 are not** -- two are a straight line of four plates
# (normalised ((0,0),(5,0),(10,0),(15,0))) and one is an L. An earlier draft of
# this comment said all the rest were translations; the translation check in
# `report()` was added to make the claim checkable and refuted it on the first
# run (observations #12).
#
# Two further facts from the same scan, both bearing on open unknown #16:
# 599 of 640 parsed courses carry two or more plates, so single-plate is the
# exception in the wild; and **zero** of the 640 show two plates claiming one
# world cell when the footprint above is applied at each `world_hex_position`,
# so `world + local` is a coherent global frame rather than a per-plate
# convenience.
#
# This is a description of what the corpus contains. It is **not** a claim that
# the app requires this arrangement, nor that connection composes across a plate
# boundary -- that is open unknown #17. On the claim side `graph.py` holds every
# course with more than one baseplate at `UNMEASURED`. Note the level: it is
# `start_goal_status` that does so, not `classify_pair`, which sends only
# *cross-layer* pairs there -- a same-plate pair on a four-plate course was
# classified exactly as on a single-plate one until that guard was added.
STANDARD_SQUARE: tuple[tuple[int, int], ...] = (
    (0, 0),
    (3, -6),
    (5, 0),
    (8, -6),
)


class UnmeasuredLayerKindError(LookupError):
    """Raised when a layer kind's footprint has never been observed in the corpus."""

    def __init__(self, kind: LayerKind) -> None:
        self.kind = kind
        super().__init__(
            f"{kind.name} has no measured footprint; "
            f"measured kinds: {sorted(k.name for k in MEASURED_FOOTPRINTS)}. "
            "Zero corpus observations means invisible, not absent -- this is a "
            "refusal to answer, not an empty plate. Re-run "
            "scripts/probe_plate_footprint.py against a corpus that contains it."
        )


def plate_footprint(kind: LayerKind) -> frozenset[tuple[int, int]]:
    """The local `(y, x)` cells `kind` is measured to occupy."""
    try:
        return MEASURED_FOOTPRINTS[kind]
    except KeyError:
        raise UnmeasuredLayerKindError(kind) from None


def is_on_plate(kind: LayerKind, local_pos: HexVector) -> bool:
    """Whether `local_pos` is a cell the corpus shows occupied on `kind`.

    Raises `UnmeasuredLayerKindError` for a kind with no measured footprint,
    rather than reporting every one of its cells as off-plate.
    """
    return (local_pos.y, local_pos.x) in plate_footprint(kind)


def plate_available_directions(kind: LayerKind, local_pos: HexVector) -> frozenset[int]:
    """The directions from `local_pos` whose neighbouring cell is on `kind`'s plate.

    The world-fixed half of the connection conjunction (`graph.py`). At
    `BASE_LAYER_PIECE` local (0,0) this is `{E, NE, NW}` -- the plate corner
    that the live-direction table had absorbed without recording.
    """
    footprint = plate_footprint(kind)
    return frozenset(
        d for d in range(6) if _as_key(local_pos.neighbor(d)) in footprint
    )


def _as_key(pos: HexVector) -> tuple[int, int]:
    """A footprint-set key from a hex position."""
    return (pos.y, pos.x)
